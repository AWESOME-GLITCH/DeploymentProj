const DICTS: Record<L1, Dict> = { en, ar, es, hi, ru, tr, zh };

export function levelIndex(s: SubLevel | null): number {
  const order = ["PreA1.1", "PreA1.2", "A1.1", "A1.2", "A2.1", "A2.2", "B1.1", "B1.2", "B2.1", "B2.2", "C1.1", "C1.2", "C2"];
  return s ? order.indexOf(s) : 4;
}

/** Which language the interface should use, following the L1 rule. */
export function uiLanguage(l1: L1, level: SubLevel | null, override: "auto" | "full" | "english"): L1 {
  if (l1 === "en") return "en";
  if (override === "full") return l1;
  if (override === "english") return "en";
  return levelIndex(level) <= 5 ? l1 : "en"; // up to A2.2 full L1
}

/** Whether tap-to-translate should be offered (B1 and above with English UI). */
export function tapToTranslate(l1: L1, level: SubLevel | null, override: "auto" | "full" | "english"): boolean {
  return l1 !== "en" && uiLanguage(l1, level, override) === "en";
}

export function makeT(lang: L1) {
  const d = DICTS[lang] ?? en;
  return (key: string): string => d[key] ?? en[key] ?? key;
}

export function loc(text: Localised | undefined, lang: L1): string {
  if (!text) return "";
  return text[lang] ?? text.en;
}

export function strandName(s: Strand, lang: L1): string {
  return makeT(lang)(`strand_${s}`);
}

export function isRtl(lang: L1): boolean {
  return lang === "ar";
}

