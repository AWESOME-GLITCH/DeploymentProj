// Turn the pre-rendered cast in docs/design/cast/ into importable modules,
// components/learning-path/art/cast-faces.ts and cast-doodles.ts.
//
//   node scripts/design/build-cast-module.cjs
//
// Why a generated module and not an import of the .svg files: the app is
// Next.js without SVGR, and the Remotion compositions have to draw every frame
// with no network at all, so the art has to be plain strings the bundler can
// see. The board's rule (docs/design/brief.md, "Illustration source") is that
// the cast is never redrawn, so this script only ever copies: it strips the
// repeated licence block, namespaces the internal ids (every Open Peeps file
// reuses "viewboxMask", so two faces on one page would mask each other), and
// collapses the whitespace between tags. No path data is touched.
//
// Faces and doodles go to separate files so a screen that only talks to
// Character() can tree-shake the 33 full-body figures away.
"use strict";

const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..", "..");
const CAST = path.join(root, "docs", "design", "cast");
const ART = path.join(root, "components", "learning-path", "art");

const NAMES = ["maya", "leo", "fatima", "sami", "you"];
const EXPRESSIONS = ["idle", "talk", "listen", "happy", "wow", "think", "oops", "laugh", "cheeky"];

/** Pull the inner markup out of one cast file, with its ids made unique. */
function read(file, prefix) {
  const raw = fs.readFileSync(path.join(CAST, file), "utf8");
  const open = raw.match(/<svg\b[^>]*>/);
  if (!open) throw new Error(`no <svg> root in ${file}`);
  const viewBox = (open[0].match(/viewBox="([^"]+)"/) || [])[1];
  if (!viewBox) throw new Error(`no viewBox in ${file}`);

  let inner = raw.slice(open.index + open[0].length, raw.lastIndexOf("</svg>"));
  inner = inner.replace(/<metadata[\s\S]*?<\/metadata>/g, "");

  const ids = new Set();
  inner.replace(/\bid="([^"]+)"/g, (_, id) => ids.add(id));
  for (const id of ids) {
    const safe = id.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    inner = inner
      .replace(new RegExp(`\\bid="${safe}"`, "g"), `id="${prefix}-${id}"`)
      .replace(new RegExp(`url\\(#${safe}\\)`, "g"), `url(#${prefix}-${id})`)
      .replace(new RegExp(`href="#${safe}"`, "g"), `href="#${prefix}-${id}"`);
  }

  inner = inner.replace(/>\s+</g, "><").trim();
  // The strings land in a TS file, so only these two characters need care.
  return { viewBox, inner: inner.replace(/\\/g, "\\\\").replace(/"/g, '\\"') };
}

const faces = [];
let faceViewBox = null;
for (const name of NAMES) {
  for (const expression of EXPRESSIONS) {
    const key = `${name}-${expression}`;
    const { viewBox, inner } = read(`${key}.svg`, key);
    if (faceViewBox && viewBox !== faceViewBox) {
      throw new Error(`${key} has viewBox ${viewBox}, expected ${faceViewBox}`);
    }
    faceViewBox = viewBox;
    faces.push([key, inner]);
  }
}

const doodles = fs
  .readdirSync(CAST)
  .filter((f) => /^doodle-.*\.svg$/.test(f))
  .sort()
  .map((f) => {
    const key = f.replace(/^doodle-/, "").replace(/\.svg$/, "");
    const { viewBox, inner } = read(f, `d-${key}`);
    return [key, viewBox, inner];
  });

const header = (what, source) => [
  "// GENERATED by scripts/design/build-cast-module.cjs. Do not hand-edit.",
  "//",
  `// ${what} from docs/design/cast/, inlined so components can draw them with`,
  `// no network at all. ${source} (CC0, Pablo Stanley), recoloured to the`,
  "// palette by scripts/lp/cast.mjs. Wrapped for use by art/characters.tsx.",
  "",
];

const list = (xs) => xs.map((x) => `"${x}"`).join(", ");

const facesFile = [
  ...header("The cast faces", "Open Peeps"),
  `export const CAST_NAMES = [${list(NAMES)}] as const;`,
  `export const EXPRESSIONS = [${list(EXPRESSIONS)}] as const;`,
  "",
  "export type CastName = (typeof CAST_NAMES)[number];",
  "export type Expression = (typeof EXPRESSIONS)[number];",
  "",
  `export const FACE_VIEWBOX = "${faceViewBox}";`,
  "",
  "/** Inner markup of one face, keyed `${name}-${expression}`. */",
  "export const FACES: Record<`${CastName}-${Expression}`, string> = {",
  ...faces.map(([key, inner]) => `  "${key}": "${inner}",`),
  "};",
  "",
].join("\n");

const doodlesFile = [
  ...header("The full-body hero figures", "Open Doodles"),
  `export const DOODLE_NAMES = [${list(doodles.map((d) => d[0]))}] as const;`,
  "",
  "export type DoodleName = (typeof DOODLE_NAMES)[number];",
  "",
  "/** Inner markup of one doodle, with its own viewBox. */",
  "export const DOODLES: Record<DoodleName, { viewBox: string; inner: string }> = {",
  ...doodles.map(([key, viewBox, inner]) => `  "${key}": { viewBox: "${viewBox}", inner: "${inner}" },`),
  "};",
  "",
].join("\n");

const kb = (p) => `${(fs.statSync(p).size / 1024).toFixed(0)} kB`;
const facesOut = path.join(ART, "cast-faces.ts");
const doodlesOut = path.join(ART, "cast-doodles.ts");
fs.writeFileSync(facesOut, facesFile);
fs.writeFileSync(doodlesOut, doodlesFile);
console.log(`cast-faces.ts:   ${faces.length} faces   ${kb(facesOut)}`);
console.log(`cast-doodles.ts: ${doodles.length} doodles ${kb(doodlesOut)}`);
