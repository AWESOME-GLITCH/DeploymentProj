#!/usr/bin/env node
/**
 * Generate components/learning-path/art/cast.tsx from docs/design/cast/.
 *
 * The board's rule (docs/design/brief.md, "Illustration source") is that the
 * characters are the pre-rendered Open Peeps faces and Open Doodles figures,
 * inlined as SVG and never redrawn. The app is a bundled Next route, so the
 * art has to arrive as a module rather than as a file the browser fetches:
 * that way a face swap on the syllable beat is a class change, not a request.
 *
 *   node scripts/design/build-cast-tsx.cjs
 *
 * Only the faces and figures the app actually uses are inlined, so the bundle
 * carries the cast it shows and nothing else. Add a name here, re-run, commit.
 */
"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..", "..");
const CAST = path.join(ROOT, "docs", "design", "cast");
const OUT = path.join(ROOT, "components", "learning-path", "art", "cast.tsx");

// Maya is the coach on Today and in every spoken turn. The expressions follow
// the brief: idle and talk alternate while she speaks, listen carries the
// lean-in, happy and wow are the reactions, oops is the only thing a miss gets.
const FACES = ["idle", "talk", "listen", "happy", "wow", "oops"];
const WHO = ["maya"];
// Full-body hero moments: the reward card and the welcome back.
const DOODLES = ["jumping", "strolling"];

/** One pre-rendered file as a self-contained markup string with scoped ids. */
function read(name, tag) {
  const raw = fs.readFileSync(path.join(CAST, name + ".svg"), "utf8");
  const open = raw.match(/<svg\b[^>]*>/);
  if (!open) throw new Error("no root <svg> in " + name);
  const viewBox = (open[0].match(/viewBox="([^"]+)"/) || [])[1];
  if (!viewBox) throw new Error("no viewBox in " + name);

  let inner = raw.slice(open.index + open[0].length, raw.lastIndexOf("</svg>"));
  // One credit in the module header is enough; the per-file block is identical.
  inner = inner.replace(/<metadata[\s\S]*?<\/metadata>/g, "");
  // Every pre-rendered file reuses the same internal ids, so scope them: two
  // faces are mounted at once for the swap and would otherwise share a mask.
  for (const id of new Set([...inner.matchAll(/id="([^"]+)"/g)].map((m) => m[1]))) {
    inner = inner.split(`id="${id}"`).join(`id="${id}-${tag}"`).split(`url(#${id})`).join(`url(#${id}-${tag})`);
  }
  return { viewBox, inner: inner.trim() };
}

const entries = [];
for (const who of WHO) {
  for (const face of FACES) entries.push({ key: `${who}-${face}`, file: `${who}-${face}` });
}
for (const d of DOODLES) entries.push({ key: `doodle-${d}`, file: `doodle-${d}` });

const art = entries.map((e, i) => {
  const { viewBox, inner } = read(e.file, String(i + 1));
  return `  "${e.key}": { viewBox: ${JSON.stringify(viewBox)}, markup: ${JSON.stringify(inner)} },`;
});

const out = `// GENERATED by scripts/design/build-cast-tsx.cjs. Do not edit by hand:
// re-run the script after changing docs/design/cast/.
//
// The pre-rendered cast, inlined. Faces are Open Peeps by Pablo Stanley and the
// full-body figures are Open Doodles, both CC0, re-coloured into the brief
// palette by scripts/lp/cast.mjs. The board's rule is that these are never
// redrawn: a screen either shows one of these or shows no character.

export type CastFace = ${FACES.map((f) => `"${f}"`).join(" | ")};
export type CastWho = ${WHO.map((w) => `"${w}"`).join(" | ")};
export type CastDoodle = ${DOODLES.map((d) => `"${d}"`).join(" | ")};

type Art = { viewBox: string; markup: string };

const ART: Record<string, Art> = {
${art.join("\n")}
};

/**
 * One piece of the cast, cropped by the box it is given.
 *
 * \`fit\` is the preserveAspectRatio: the brief wants the character oversized and
 * cropped with confidence, so a face is usually "xMidYMin slice" inside a card
 * that is shorter than the art is tall.
 */
export function Cast({ art, className, style, fit = "xMidYMin slice", title }: {
  art: string;
  className?: string;
  style?: React.CSSProperties;
  fit?: string;
  title?: string;
}) {
  const piece = ART[art];
  if (!piece) return null;
  return (
    <svg
      viewBox={piece.viewBox}
      preserveAspectRatio={fit}
      className={className}
      style={style}
      role={title ? "img" : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : true}
      focusable="false"
      dangerouslySetInnerHTML={{ __html: piece.markup }}
    />
  );
}

/** \`maya\` with the face named: the call site reads as the expression it wants. */
export function Face({ who = "maya", face, ...rest }: { who?: CastWho; face: CastFace } & Omit<Parameters<typeof Cast>[0], "art">) {
  return <Cast art={\`\${who}-\${face}\`} {...rest} />;
}

/** A full-body hero figure for the moments that earn one. */
export function Doodle({ doodle, ...rest }: { doodle: CastDoodle } & Omit<Parameters<typeof Cast>[0], "art">) {
  return <Cast art={\`doodle-\${doodle}\`} {...rest} />;
}
`;

fs.writeFileSync(OUT, out);
console.log(`${OUT}  ${(out.length / 1024).toFixed(0)} kB, ${entries.length} pieces`);
