#!/usr/bin/env node
/**
 * Inline the pre-rendered cast into a standalone prototype.
 *
 * The board's rule (docs/design/brief.md, "Illustration source") is that the
 * characters are the Open Peeps faces and Open Doodles figures in
 * docs/design/cast/, inlined as SVG and never redrawn. The prototypes are
 * single files, so the art has to live inside the HTML.
 *
 * Usage: node scripts/design/inline-cast.cjs docs/prototypes/02-explainer.html
 *
 * The target file declares what it needs and where the art goes:
 *
 *   <!--cast:need leo-idle,leo-talk,you-idle-->
 *   <!--cast:start-->...generated symbols...<!--cast:end-->
 *
 * Re-running is safe: the block between the markers is replaced each time.
 */
"use strict";

const fs = require("fs");
const path = require("path");

const CAST_DIR = path.join(__dirname, "..", "..", "docs", "design", "cast");

function symbolFor(name) {
  const file = path.join(CAST_DIR, name + ".svg");
  const raw = fs.readFileSync(file, "utf8");

  const open = raw.match(/<svg\b[^>]*>/);
  if (!open) throw new Error("no root svg in " + file);
  const viewBox = (open[0].match(/viewBox="([^"]+)"/) || [])[1];
  if (!viewBox) throw new Error("no viewBox in " + file);

  let inner = raw.slice(open.index + open[0].length, raw.lastIndexOf("</svg>"));
  // the licence block is repeated in every file; one credit in the HTML is enough
  inner = inner.replace(/<metadata[\s\S]*?<\/metadata>/g, "");

  // every Open Peeps file uses the same internal ids, so namespace them
  const ids = new Set();
  inner.replace(/\sid="([^"]+)"/g, (m, id) => ids.add(id));
  for (const id of ids) {
    const safe = id.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    inner = inner
      .replace(new RegExp(' id="' + safe + '"', "g"), ' id="' + name + "-" + id + '"')
      .replace(new RegExp("url\\(#" + safe + "\\)", "g"), "url(#" + name + "-" + id + ")");
  }

  return '<symbol id="c-' + name + '" viewBox="' + viewBox + '">' + inner.trim() + "</symbol>";
}

function main() {
  const target = process.argv[2];
  if (!target) {
    console.error("usage: node scripts/design/inline-cast.cjs <file.html>");
    process.exit(1);
  }
  const html = fs.readFileSync(target, "utf8");

  const need = html.match(/<!--cast:need\s+([^>]+?)-->/);
  if (!need) throw new Error("no <!--cast:need ...--> comment in " + target);
  const names = need[1].split(",").map((s) => s.trim()).filter(Boolean);

  const start = html.indexOf("<!--cast:start-->");
  const end = html.indexOf("<!--cast:end-->");
  if (start < 0 || end < 0) throw new Error("no cast:start / cast:end markers in " + target);

  const credit =
    "<!-- Cast: Open Peeps by Pablo Stanley (CC0), recoloured to the palette. " +
    "Generated by scripts/design/inline-cast.cjs, do not hand-edit. -->";
  const body = credit + names.map(symbolFor).join("");

  const out =
    html.slice(0, start) + "<!--cast:start-->" + body + html.slice(end);
  fs.writeFileSync(target, out);

  const kb = Math.round(Buffer.byteLength(out) / 1024);
  console.log("inlined " + names.length + " cast files into " + target + " (" + kb + " kB)");
}

main();
